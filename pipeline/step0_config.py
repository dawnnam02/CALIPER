"""단계 0 — 모든 설정을 여기 한 곳에 모은다.

이 파일의 값만 바꾸면 파이프라인 전체가 그 값으로 돈다.
다른 파일은 건드릴 필요가 없다.

=============================================================================
읽는 법
=============================================================================
아래 값들은 크게 세 종류다.

  (1) 표적에 따라 반드시 바꿔야 하는 것   → TARGET_*
  (2) 관례적으로 쓰는 값                  → 그대로 두면 된다
  (3) 필터 임계값                         → 문헌값이지만 실측으로 확인했다.
                                            VALIDATION.md 를 먼저 읽을 것

Step 0 - every setting lives here. Change values in this file only.
"""

from pathlib import Path

# =============================================================================
# 어디에 결과를 쌓을 것인가
# =============================================================================

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "work"                 # 중간 산출물이 전부 여기 쌓인다

DIR_TARGET   = WORK / "1_target"     # 손질한 표적 구조
DIR_BACKBONE = WORK / "2_backbone"   # RFdiffusion 이 뱉은 골격 PDB
DIR_SEQUENCE = WORK / "3_sequence"   # ProteinMPNN 이 뱉은 서열 FASTA
DIR_PREDICT  = WORK / "4_predict"    # AF2 예측 구조와 점수
DIR_FILTER   = WORK / "5_filter"     # 필터 통과 목록
DIR_ORDER    = WORK / "6_order"      # 실험 발주 파일

ALL_DIRS = [DIR_TARGET, DIR_BACKBONE, DIR_SEQUENCE,
            DIR_PREDICT, DIR_FILTER, DIR_ORDER]


# =============================================================================
# (1) 표적 — 여기는 반드시 네가 채워야 한다
# =============================================================================

# 표적 구조 파일. PDB 에서 받거나 AlphaFold DB 에서 받는다.
# 기본값은 실제로 돌아가는 예제다: MDM2 (PDB 1YCR 의 사슬 A).
# p53 이 꽂히는 소수성 주머니가 잘 알려져 있어서 핫스팟 예시로 좋다.
#   받기:  python scripts/get_example_target.py
TARGET_PDB = ROOT / "data" / "targets" / "1ycr.pdb"

# 표적 구조에서 결합체를 붙이고 싶은 쪽의 사슬(chain) 이름
TARGET_CHAIN = "A"

# 핫스팟(hotspot) — 결합체가 반드시 닿았으면 하는 표적 잔기 번호.
#
#   왜 필요한가: 지정하지 않으면 RFdiffusion 이 표적 아무 데나 붙는 골격을
#   만든다. 대부분은 우리가 원하지 않는 면이다. 기능적으로 의미 있는
#   자리(리간드가 붙는 곳, 항체가 붙는 곳)를 직접 골라줘야 한다.
#
#   몇 개를 고르나: 보통 3~5개. 너무 적으면 방향이 안 잡히고,
#   너무 많으면 만족시킬 골격이 없어서 생성이 실패한다.
#
#   어떻게 고르나: → step1_target.py 의 주석을 읽을 것
# MDM2 의 p53 결합 주머니를 이루는 잔기들.
# Leu54 · Met62 · Val93 · Ile99 — 전부 소수성이고 오목한 자리에 있다.
TARGET_HOTSPOTS = [54, 62, 93, 99]

# 표적을 통째로 넣으면 느리다. 핫스팟 주변만 잘라 쓴다.
TARGET_TRIM_RADIUS = 20.0            # 옹스트롬(Å). 핫스팟에서 이 거리 안쪽만 남긴다


# =============================================================================
# (2) 골격 생성 — RFdiffusion
# =============================================================================

# 결합체 길이 범위. 짧으면 발현이 쉽고 길면 접촉 면적이 넓다.
# 55~100 이 관례. 이보다 짧으면 안정적인 접힘을 만들기 어렵다.
BINDER_LENGTH_MIN = 55
BINDER_LENGTH_MAX = 100

# 골격을 몇 개나 만들 것인가.
#
#   현실적인 숫자: 최종적으로 웰 96개를 채우려면 골격 수천 개에서 시작한다.
#   뒤 단계에서 대부분 걸러지기 때문이다. 아래 '깔때기' 표 참조.
N_BACKBONES = 1000

# 노이즈 스케일. 결합체 설계에서는 0 으로 둔다.
#
#   왜 0인가: 기본값(1.0)은 다양성을 위해 노이즈를 넣는데, 결합체에서는
#   그 다양성이 오히려 성공률을 떨어뜨린다는 것이 실측됐다.
#   (Watson et al. 2023, RFdiffusion 논문의 binder 절)
#   자주 놓치는 설정이다.
RFDIFFUSION_NOISE_SCALE = 0.0

RFDIFFUSION_DIFFUSER_T = 50          # 확산 스텝 수. 50이 관례


# =============================================================================
# (3) 서열 설계 — ProteinMPNN
# =============================================================================

# 골격 하나당 서열 몇 개를 뽑을 것인가. 8이 관례.
SEQS_PER_BACKBONE = 8

# 샘플링 온도. 낮을수록 안전하고 비슷한 서열, 높을수록 다양하고 위험하다.
MPNN_TEMPERATURE = 0.1

# soluble 가중치를 쓸 것인가.
#
#   왜 중요한가: 기본 ProteinMPNN 은 PDB 로 학습됐는데, PDB 구조는
#   대부분 막단백질이나 복합체라서 표면에 소수성(기름 성질) 잔기가 많다.
#   그걸 그대로 배우면 물에 안 녹는 단백질이 나온다.
#   soluble 가중치는 그 편향을 줄인 것이다. 결합체 설계에서는 이걸 쓴다.
MPNN_USE_SOLUBLE_WEIGHTS = True


# =============================================================================
# (4) 구조 검증 — AlphaFold2 initial guess
# =============================================================================

# initial guess 를 쓸 것인가.
#
#   이게 이 파이프라인에서 가장 중요한 한 줄이다.
#   보통의 AF2 는 서열만 보고 구조를 처음부터 예측한다. initial guess 는
#   "우리가 설계한 복합체 구조"를 출발점으로 주고 예측하게 한다.
#   Bennett et al. 2023 이 이 한 가지로 성공률을 약 10배 올렸다.
AF2_USE_INITIAL_GUESS = True

AF2_NUM_RECYCLES = 3
AF2_MODEL = "model_1_multimer_v3"    # initial guess 구현이 쓰는 모델


# =============================================================================
# (5) 필터 임계값 — 여기는 반드시 VALIDATION.md 를 읽고 만질 것
# =============================================================================
#
# 아래 값들은 문헌의 관례값이다. 그런데 실측 데이터 60만 개로 확인해 보니
# **표적마다 통과율이 0%에서 23%까지 벌어졌다.** 어떤 표적에서는
# 이 필터가 라이브러리를 통째로 죽인다.
#
# 그래서 파이프라인은 이 값을 그냥 적용하지 않고,
# step5_filter.py 가 **통과 개수를 먼저 보고**한 뒤 진행 여부를 묻는다.
# 자세한 근거 → VALIDATION.md

# 계면 pAE (predicted aligned error, 예측 정렬 오차) — 낮을수록 좋다.
#   두 사슬 사이의 위치를 AF2 가 얼마나 확신하는지. 이 파이프라인의 주 필터.
#   근거: Bennett et al. 2023
FILTER_PAE_INTERACTION_MAX = 10.0

# 결합체 단독의 pLDDT — 높을수록 좋다. 접힘 자체가 믿을 만한가.
#   ⚠️ 실측에서 이 필터 단독으로는 농축 효과가 거의 없었다 (0.9~1.0배).
#      버리진 않되 이걸로 거르고 있다고 착각하면 안 된다.
FILTER_PLDDT_BINDER_MIN = 80.0

# 설계한 골격과 AF2 예측 구조의 어긋남(RMSD) — 낮을수록 좋다.
#   "우리가 그린 대로 접히는가". 실측에서 pAE 보다 오히려 농축이 셌다.
FILTER_RMSD_MAX = 2.0

# 최종적으로 실험에 보낼 개수
N_TO_ORDER = 96


# =============================================================================
# (6) 실험 발주
# =============================================================================

PLATE_SIZE = 96                      # 96웰 플레이트 한 판

# 대조군을 반드시 넣는다. 이게 없으면 실험이 실패했을 때
# "설계가 나쁜 건지 실험이 잘못된 건지" 구분할 방법이 없다.
N_POSITIVE_CONTROLS = 2              # 이미 붙는 걸 아는 것 (항체, 천연 리간드)
N_NEGATIVE_CONTROLS = 2              # 안 붙는 게 확실한 것

# 서열 다양성 하한. 이보다 비슷한 것끼리는 하나만 남긴다.
#   왜: 골격 하나에서 서열 8개를 뽑았으니 그냥 상위 96개를 고르면
#   골격 12개짜리 실험이 되어버린다. 하나가 틀리면 8개가 같이 틀린다.
MAX_SEQUENCE_IDENTITY = 0.90


# =============================================================================
# 깔때기 — 각 단계에서 몇 개가 살아남는지 (대략적인 기대치)
# =============================================================================
#
#   골격 생성        1,000 개
#   × 서열 8개    →  8,000 개
#   AF2 검증      →  8,000 개  (전부 예측은 한다. 여기가 계산비용의 대부분)
#   필터 통과     →    100~800 개   ← 표적에 따라 0개일 수도 있다
#   다양성 정리   →     50~300 개
#   발주          →     92 개 + 대조군 4개
#
# 필터 통과가 0에 가까우면 골격 수를 늘리는 게 아니라
# **핫스팟이나 표적 선택이 잘못된 것**일 가능성이 높다.
# → PIPELINE.md 의 '필터가 전부 죽일 때' 절

def ensure_dirs() -> None:
    """작업 폴더를 만든다. 각 단계 시작에서 부른다."""
    for d in ALL_DIRS:
        d.mkdir(parents=True, exist_ok=True)
